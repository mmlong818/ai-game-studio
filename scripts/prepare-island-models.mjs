// Offline asset conversion only. Runtime needs neither OBJLoader nor texture requests.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
import { OBJLoader } from 'three/addons/loaders/OBJLoader.js';
import { Color, Box3, Vector3 } from 'three';
import { PNG } from 'pngjs';

const root=resolve('assets/source-packs/kenney'), out=resolve('fixtures/island-kart/assets/models');
mkdirSync(out,{recursive:true});
const selection={
  'car-kit':['kart-oopi','kart-oodi','kart-oobi'],
  'nature-kit':['tree_palmDetailedTall','tree_palmBend','plant_bushDetailed','rock_smallC','rock_largeA','flower_redA'],
};
const models={}, manifest=[];
for(const [pack,names] of Object.entries(selection)) {
  copyFileSync(join(root,pack,'License.txt'),join(out,pack+'-LICENSE.txt'));
  for(const name of names) {
    const folder=join(root,pack,'Models','OBJ format'), source=readFileSync(join(folder,name+'.obj'),'utf8');
    const materials={};let current;
    for(const line of readFileSync(join(folder,name+'.mtl'),'utf8').split(/\r?\n/)) {
      if(line.startsWith('newmtl ')) { current={color:new Color(1,1,1)};materials[line.slice(7).trim()]=current; }
      if(line.startsWith('Kd ')) {const rgb=line.slice(3).trim().split(/\s+/).map(Number);current.color.setRGB(...rgb).convertSRGBToLinear();}
      if(line.startsWith('map_Kd ')) current.texture=PNG.sync.read(readFileSync(join(folder,line.slice(7).trim())));
    }
    const obj=new OBJLoader().parse(source), bounds=new Box3().setFromObject(obj), size=bounds.getSize(new Vector3());
    const parts=[];let triangles=0;
    obj.traverse(m=>{
      if(!m.isMesh)return;
      const g=m.geometry.index?m.geometry.toNonIndexed():m.geometry, a=g.attributes;
      const data={name:m.name,position:[],normal:[],color:[]};
      for(let i=0;i<a.position.count;i++) {
        const group=g.groups.find(t=>i>=t.start&&i<t.start+t.count);
        const mat=Array.isArray(m.material)?m.material[group?.materialIndex??0]:m.material;
        const def=materials[mat.name]; if(!def)throw new Error('Unknown material '+mat.name);
        const color=def.color.clone();
        if(def.texture) {
          const p=def.texture, u=a.uv.getX(i), v=a.uv.getY(i);
          const x=Math.max(0,Math.min(p.width-1,Math.floor(u*p.width))), y=Math.max(0,Math.min(p.height-1,Math.floor((1-v)*p.height)));
          const n=(y*p.width+x)*4;color.setRGB(p.data[n]/255,p.data[n+1]/255,p.data[n+2]/255).convertSRGBToLinear();
        }
        // Adapt the licensed palettes to this game's teal/coral/gold identity.
        if(pack==='nature-kit') {
          if(/leaf|green|grass/i.test(mat.name))color.set('#499b69');
          if(/wood|bark/i.test(mat.name))color.set('#ad8057');
        } else {
          const team=new Color({'kart-oopi':'#21bcb1','kart-oodi':'#ed8ca1','kart-oobi':'#eed05c'}[name]);
          const srgb=color.clone().convertLinearToSRGB();
          if(partIsHelmet(m.name,a.position,i,srgb))color.copy(Math.abs(a.position.getX(i))<.045?new Color('#fff7dd'):team.clone().lerp(new Color('#fff7dd'),.35));
          else if(m.name.startsWith('kart-') && srgb.b>srgb.r*1.12 && srgb.b>srgb.g*1.12)color.copy(team);
        }
        data.position.push(a.position.getX(i),a.position.getY(i),a.position.getZ(i));
        data.normal.push(a.normal.getX(i),a.normal.getY(i),a.normal.getZ(i));
        data.color.push(color.r,color.g,color.b);
      }
      for(const key of ['position','normal','color'])data[key]=data[key].map(n=>Math.round(n*10000)/10000);
      triangles+=a.position.count/3;parts.push(data);
    });
    models[name]={parts,size:size.toArray(),min:bounds.min.toArray()};
    manifest.push({name,pack,license:'CC0-1.0',source:`https://kenney.nl/assets/${pack}`,sha256:createHash('sha256').update(source).digest('hex'),triangles});
  }
}
writeFileSync(join(out,'kenney-models.js'),'// Generated by scripts/prepare-island-models.mjs; Kenney CC0.\nexport const models='+JSON.stringify(models)+';\n');
writeFileSync(join(out,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(manifest);

function partIsHelmet(name,position,index,color) {
  return name==='character' && position.getY(index)>.68 && Math.min(color.r,color.g,color.b)>.7;
}
